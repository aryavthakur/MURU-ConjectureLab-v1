def falsification_harness(worlds) -> str:
    ok = [w for w in worlds if w.get("status") == "ok" and w.get("harness")]
    counts = defaultdict(lambda: [0, 0])
    for w in ok:
        for k, passed in w["harness"]["required_results"].items():
            counts[k][1] += 1
            counts[k][0] += bool(passed)
    rows = [f"| `{k}` | {falsify.REQUIRED.index(k) if k in falsify.REQUIRED else '-'} "
            f"| {v[0]}/{v[1]} |" for k, v in sorted(counts.items())]
    fail = defaultdict(int)
    for w in ok:
        for k in w["harness"]["failed_rungs"]:
            fail[k] += 1
    return f"""# FALSIFICATION_HARNESS.md

{prereg_header()}
F1–F12 run as an automated ladder with machine-readable pass/fail per rung. A
candidate must survive the complete **required** set. This is not a "validation
score": each rung tests a distinct way the candidate could be an artifact.

## Rung status

| Rung | Test | Status |
|---|---|---|
| F1 | reproducibility of the recorded artifact | **required** |
| F2 | invariance to a defensible change in the estimation pipeline | **required** |
| F3 | source-branch invariance | **not applicable** |
| F4 | compound holdout | **required** |
| F5 | scaffold holdout — **primary claim gate** | **required** |
| F6 | similarity-cluster holdout | **required** |
| F7 | influence robustness (top 5% dropped, leave-one-mix-out) | **required** |
| F8 | descriptor ablation, mass block removed together | **labelling** |
| F9 | energy-subset stability | **required** |
| F10 | negative controls — the candidate must FAIL on permuted targets | **required** |
| F11 | mode replication | **not applicable** |
| F12 | extrapolation probe | **supporting only** |

A rung recorded `not_applicable` is **never** counted as a pass.

**F3** has no synthetic counterpart: a synthetic response has no intensity
cutoff, no annotation filter and no raw branch. The real raw branch covers 39
compounds (7.1%) and licenses no corpus-level preprocessing-invariance claim in
any case. **F11** is not evaluable because the generators are mode-agnostic;
Phase 2's negative-mode K4B failure remains binding regardless.

**F8 labels, it does not reject.** Master plan 16.1: if removing precursor mass
destroys the result, the "law" *is* a mass law and is reported as such. F8 gates
only a claim of structure **beyond** mass, using the Phase 2 mass block
`{{{', '.join(protocol.MASS_BLOCK)}}}` removed together — dropping the named mass
variable alone would leave its proxies in place.

**F12 is never a gate.** Six energy levels cannot support an extrapolation
requirement.

## Observed rung outcomes across {len(ok)} adjudicated candidates

| Rung | Required | Passed |
|---|---|---|
{chr(10).join(rows)}

Most common failure: {', '.join(f'`{k}` ({v})' for k, v in sorted(fail.items(), key=lambda x: -x[1])[:5]) or 'none'}.

## Constant re-fitting

The collapse target identifies `g` only up to a positive multiplicative
constant, so each rung re-fits the candidate's **affine scale and offset** by
weighted least squares on the **training** partition only, then evaluates on the
holdout. That is exactly the freedom the science allows and no more.

## The harness is itself tested

`tests/test_p3_falsify.py` builds small worlds with known answers and requires
the ladder to pass the genuine relationship, reject a deliberately planted
artifact expression, reject a constant, reject a high-complexity interpolant
built from signal-free descriptors, identify mass as the carrier in a mass-only
world, and destroy the true law under permuted targets.
"""


