def load(name):
    p = ART / name
    return json.loads(p.read_text()) if p.exists() else None


def prereg_header() -> str:
    sha = hashlib.sha256((ROOT / "PHASE3_PREREGISTRATION.md").read_bytes()).hexdigest()
    try:
        commit = subprocess.run(
            ["git", "log", "-1", "--format=%H", "--", "PHASE3_PREREGISTRATION.md"],
            cwd=ROOT, capture_output=True, text=True).stdout.strip()
    except Exception:
        commit = "unknown"
    return (f"Generated by `scripts/t3_50_reports.py` from machine-readable Phase 3\n"
            f"artifacts. Pre-registration: `PHASE3_PREREGISTRATION.md`\n"
            f"(sha256 `{sha}`,\ncommitted `{commit}`), frozen **before** any "
            f"governed symbolic run.\n")


def by_block(worlds):
    d = defaultdict(list)
    for w in worlds:
        if w.get("status") == "ok":
            d[w["block"]].append(w)
    return d


