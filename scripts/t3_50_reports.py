def main() -> int:
    worlds = load("p3_worlds.json") or []
    cal = load("p3_null_calibration.json")
    fp = load("p3_false_positives.json")
    env = load("p3_engine_validation.json")

    written = []
    if worlds:
        (ROOT / "SYNTHETIC_GENERATORS.md").write_text(synthetic_generators(worlds))
        (ROOT / "FALSIFICATION_HARNESS.md").write_text(falsification_harness(worlds))
        written += ["SYNTHETIC_GENERATORS.md", "FALSIFICATION_HARNESS.md"]
    if env:
        (ROOT / "ENGINE_VALIDATION.md").write_text(engine_validation(env))
        written.append("ENGINE_VALIDATION.md")
    if env and worlds:
        (ROOT / "SYMBOLIC_SEARCH_SPEC.md").write_text(symbolic_search_spec(env, worlds))
        written.append("SYMBOLIC_SEARCH_SPEC.md")
    if cal and fp:
        (ROOT / "NULL_CALIBRATION.md").write_text(null_calibration(cal, fp))
        written.append("NULL_CALIBRATION.md")
    if cal:
        md, obj = frozen_protocol(cal, worlds)
        (ROOT / "PHASE4_FROZEN_DISCOVERY_PROTOCOL.md").write_text(md)
        (ART / "phase4_frozen_protocol.json").write_text(json.dumps(obj, indent=1))
        written += ["PHASE4_FROZEN_DISCOVERY_PROTOCOL.md",
                    "artifacts/phase4_frozen_protocol.json"]
    print("[t3_50] wrote " + ", ".join(written))
    return 0


